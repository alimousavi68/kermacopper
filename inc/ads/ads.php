function kermancopper_ads_handle_request_verify() {
    if ( $_SERVER['REQUEST_METHOD'] !== 'POST' ) {
        if ( wp_doing_ajax() ) {
            wp_send_json_error( array( 'code' => 'invalid_request', 'message' => 'درخواست نامعتبر است.' ), 400 );
        }
        wp_safe_redirect( home_url( '/' ) );
        exit;
    }
    $ad_id = isset( $_POST['ad_id'] ) ? absint( $_POST['ad_id'] ) : 0;
    $redirect_url = $ad_id ? get_permalink( $ad_id ) : home_url( '/' );
    if ( ! $ad_id || get_post_type( $ad_id ) !== 'kermancopper_ad' ) {
        if ( wp_doing_ajax() ) {
            wp_send_json_error( array( 'code' => 'invalid_ad', 'message' => 'آگهی معتبر نیست.' ), 400 );
        }
        wp_safe_redirect( add_query_arg( 'ad_request', 'invalid_ad', $redirect_url ) );
        exit;
    }
    $nonce = isset( $_POST['kermancopper_ad_request_verify_nonce'] ) ? sanitize_text_field( wp_unslash( $_POST['kermancopper_ad_request_verify_nonce'] ) ) : '';
    if ( ! wp_verify_nonce( $nonce, 'kermancopper_ad_request_verify' ) ) {
        if ( wp_doing_ajax() ) {
            wp_send_json_error( array( 'code' => 'invalid_nonce', 'message' => 'اعتبار فرم منقضی شده است. دوباره تلاش کنید.' ), 400 );
        }
        wp_safe_redirect( add_query_arg( 'ad_request', 'invalid_nonce', $redirect_url ) );
        exit;
    }
    $otp_token = isset( $_POST['ad_request_token'] ) ? sanitize_text_field( wp_unslash( $_POST['ad_request_token'] ) ) : '';
    if ( $otp_token === '' ) {
        if ( wp_doing_ajax() ) {
            wp_send_json_error( array( 'code' => 'otp_missing', 'message' => 'کد تایید یافت نشد. دوباره تلاش کنید.' ), 400 );
        }
        wp_safe_redirect( add_query_arg( 'ad_request', 'otp_missing', $redirect_url ) );
        exit;
    }
    $payload = get_transient( 'kermancopper_ad_otp_' . $otp_token );
    if ( ! is_array( $payload ) || empty( $payload['ad_id'] ) ) {
        if ( wp_doing_ajax() ) {
            wp_send_json_error( array( 'code' => 'otp_expired', 'message' => 'کد منقضی شده است. دوباره درخواست کنید.' ), 400 );
        }
        wp_safe_redirect( add_query_arg( 'ad_request', 'otp_expired', $redirect_url ) );
        exit;
    }
    if ( (int) $payload['ad_id'] !== $ad_id ) {
        if ( wp_doing_ajax() ) {
            wp_send_json_error( array( 'code' => 'invalid_ad', 'message' => 'آگهی معتبر نیست.' ), 400 );
        }
        wp_safe_redirect( add_query_arg( 'ad_request', 'invalid_ad', $redirect_url ) );
        exit;
    }
    $code = isset( $_POST['otp_code'] ) ? sanitize_text_field( wp_unslash( $_POST['otp_code'] ) ) : '';
    if ( $code === '' || (string) $payload['code'] !== $code ) {
        if ( wp_doing_ajax() ) {
            wp_send_json_error( array( 'code' => 'otp_invalid', 'message' => 'کد وارد شده صحیح نیست.' ), 400 );
        }
        $redirect_url = add_query_arg(
            array(
                'ad_request'       => 'otp_invalid',
                'ad_request_token' => $otp_token,
            ),
            $redirect_url
        );
        wp_safe_redirect( $redirect_url );
        exit;
    }
    if ( ! kermancopper_ads_is_ad_open( $ad_id ) ) {
        if ( wp_doing_ajax() ) {
            wp_send_json_error( array( 'code' => 'expired', 'message' => 'مهلت ثبت درخواست به پایان رسیده است.' ), 400 );
        }
        wp_safe_redirect( add_query_arg( 'ad_request', 'expired', $redirect_url ) );
        exit;
    }
    if ( kermancopper_ads_request_exists_for_ad( $ad_id, $payload['national_id'] ) ) {
        if ( wp_doing_ajax() ) {
            wp_send_json_error( array( 'code' => 'duplicate_national_id_for_ad', 'message' => 'شما قبلاً با این شناسه ملی در این آگهی ثبت نام کرده‌اید.' ), 400 );
        }
        delete_transient( 'kermancopper_ad_otp_' . $otp_token );
        wp_safe_redirect( add_query_arg( 'ad_request', 'duplicate_national_id_for_ad', $redirect_url ) );
        exit;
    }
    $author_id = (int) get_current_user_id();
    if ( $author_id <= 0 ) {
        $admin_email = get_option( 'admin_email' );
        if ( $admin_email ) {
            $admin_user = get_user_by( 'email', $admin_email );
            if ( $admin_user ) {
                $author_id = (int) $admin_user->ID;
            }
        }
    }
    if ( $author_id <= 0 ) {
        $admin_users = get_users(
            array(
                'role__in' => array( 'administrator' ),
                'number'   => 1,
                'fields'   => array( 'ID' ),
            )
        );
        if ( ! empty( $admin_users ) ) {
            $author_id = (int) $admin_users[0]->ID;
        }
    }
    if ( $author_id <= 0 ) {
        $any_users = get_users(
            array(
                'number' => 1,
                'fields' => array( 'ID' ),
            )
        );
        if ( ! empty( $any_users ) ) {
            $author_id = (int) $any_users[0]->ID;
        }
    }
    if ( $author_id <= 0 ) {
        $author_id = 1;
    }
    $guest_cap_filter = function ( $allcaps ) {
        $allcaps['edit_posts'] = true;
        $allcaps['publish_posts'] = true;
        $allcaps['edit_private_posts'] = true;
        return $allcaps;
    };
    add_filter( 'user_has_cap', $guest_cap_filter, 10, 1 );
    $request_id = wp_insert_post(
        array(
            'post_type'   => KERMANCOPPER_AD_REQUEST_POST_TYPE,
            'post_title'  => $payload['name'] . ' - ' . current_time( 'Y-m-d H:i' ),
            'post_status' => 'private',
            'post_author' => $author_id,
        ),
        true
    );
    remove_filter( 'user_has_cap', $guest_cap_filter, 10 );
    if ( ! $request_id || is_wp_error( $request_id ) ) {
        $detail = '';
        $error_code = '';
        if ( is_wp_error( $request_id ) ) {
            $error_code = $request_id->get_error_code();
            $messages = $request_id->get_error_messages();
            if ( ! empty( $messages ) ) {
                $detail = implode( '، ', $messages );
            } else {
                $detail = $request_id->get_error_message();
            }
        } else {
            $detail = 'ثبت درخواست ناموفق بود.';
        }
        global $wpdb;
        if ( $wpdb && ! empty( $wpdb->last_error ) ) {
            $detail = trim( $detail . ' | DB: ' . $wpdb->last_error );
        }
        if ( $error_code !== '' ) {
            $detail = trim( $detail . ' | Code: ' . $error_code );
        }
        if ( wp_doing_ajax() ) {
            wp_send_json_error(
                array(
                    'code'    => 'submit_error',
                    'message' => 'ثبت درخواست با خطا روبه‌رو شد. جزئیات: ' . $detail,
                ),
                400
            );
        }
        $redirect_url = add_query_arg(
            array(
                'ad_request'       => 'submit_error',
                'ad_request_detail' => $detail,
                'ad_request_token' => $otp_token,
            ),
            $redirect_url
        );
        delete_transient( 'kermancopper_ad_otp_' . $otp_token );
        kermancopper_ads_cleanup_attachments( $payload['attachment_ids'] );
        wp_safe_redirect( $redirect_url );
        exit;
    }
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_AD_ID, $ad_id );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_NAME, $payload['name'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_MOBILE, $payload['mobile'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_EMAIL, $payload['email'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_COMPANY, $payload['company'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_COMPANY_TYPE, $payload['company_type'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_ACTIVITY_TYPE, $payload['activity_type'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_COMPANY_NAME_EN, $payload['company_name_en'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_NATIONAL_ID, $payload['national_id'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_ESTABLISHMENT_DATE, $payload['establishment_date'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_ECONOMIC_NUMBER, $payload['economic_number'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_REGISTRATION_NUMBER, $payload['registration_number'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_REGISTRATION_LOCATION, $payload['registration_location'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_INSURANCE_BRANCH, $payload['insurance_branch'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_CEO_NAME, $payload['ceo_name'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_CEO_NATIONAL_ID, $payload['ceo_national_id'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_CEO_MOBILE, $payload['ceo_mobile'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_PHONE, $payload['phone'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_FAX, $payload['fax'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_WEBSITE, $payload['website'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_POSTAL_CODE, $payload['postal_code'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_PROVINCE, $payload['province'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_CITY, $payload['city'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_ADDRESS, $payload['address'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_BANK_SHEBA, $payload['bank_sheba'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_BANK_ACCOUNT, $payload['bank_account'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_BANK_BRANCH, $payload['bank_branch'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_REGISTRATION_REASON, $payload['registration_reason'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_NOTE, $payload['note'] );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_ATTACHMENTS, $payload['attachment_ids'] );

    // Create User Account or use existing user
    $is_existing = ! empty( $payload['is_existing_user'] );
    $user_id = $is_existing ? (int) $payload['existing_user_id'] : 0;

    if ( ! $is_existing ) {
        $user_id = wp_insert_user( array(
            'user_login' => $payload['national_id'],
            'user_pass'  => $payload['password'],
            'user_email' => $payload['email'],
            'first_name' => $payload['name'],
            'role'       => 'subscriber',
        ) );
    }

    if ( ! $user_id || is_wp_error( $user_id ) ) {
        $detail = is_wp_error( $user_id ) ? $user_id->get_error_message() : 'ایجاد یا اتصال حساب کاربری ناموفق بود.';
        wp_delete_post( $request_id, true );
        delete_transient( 'kermancopper_ad_otp_' . $otp_token );
        kermancopper_ads_cleanup_attachments( $payload['attachment_ids'] );

        if ( wp_doing_ajax() ) {
            wp_send_json_error(
                array(
                    'code'    => 'submit_error',
                    'message' => 'ثبت درخواست با خطا روبه‌رو شد. جزئیات: ' . $detail,
                ),
                400
            );
        }

        $redirect_url = add_query_arg(
            array(
                'ad_request'        => 'submit_error',
                'ad_request_detail' => $detail,
            ),
            $redirect_url
        );
        wp_safe_redirect( $redirect_url );
        exit;
    }

    // Store/Update extra fields in user meta
    update_user_meta( $user_id, 'mobile', $payload['mobile'] );
    update_user_meta( $user_id, 'company', $payload['company'] );
    update_user_meta( $user_id, 'company_type', $payload['company_type'] );
    update_user_meta( $user_id, 'activity_type', $payload['activity_type'] );
    update_user_meta( $user_id, 'company_name_en', $payload['company_name_en'] );
    update_user_meta( $user_id, 'national_id', $payload['national_id'] );
    update_user_meta( $user_id, 'establishment_date', $payload['establishment_date'] );
    update_user_meta( $user_id, 'economic_number', $payload['economic_number'] );
    update_user_meta( $user_id, 'registration_number', $payload['registration_number'] );
    update_user_meta( $user_id, 'registration_location', $payload['registration_location'] );
    update_user_meta( $user_id, 'insurance_branch', $payload['insurance_branch'] );
    update_user_meta( $user_id, 'ceo_name', $payload['ceo_name'] );
    update_user_meta( $user_id, 'ceo_national_id', $payload['ceo_national_id'] );
    update_user_meta( $user_id, 'ceo_mobile', $payload['ceo_mobile'] );
    update_user_meta( $user_id, 'phone', $payload['phone'] );
    update_user_meta( $user_id, 'fax', $payload['fax'] );
    update_user_meta( $user_id, 'website', $payload['website'] );
    update_user_meta( $user_id, 'postal_code', $payload['postal_code'] );
    update_user_meta( $user_id, 'province', $payload['province'] );
    update_user_meta( $user_id, 'city', $payload['city'] );
    update_user_meta( $user_id, 'address', $payload['address'] );
    update_user_meta( $user_id, 'bank_sheba', $payload['bank_sheba'] );
    update_user_meta( $user_id, 'bank_account', $payload['bank_account'] );
    update_user_meta( $user_id, 'bank_branch', $payload['bank_branch'] );

    // Associate request post with user
    wp_update_post( array(
        'ID'          => $request_id,
        'post_author' => $user_id,
    ) );

    // Log the user in
    wp_clear_auth_cookie();
    wp_set_current_user( $user_id );
    wp_set_auth_cookie( $user_id );
    
    $attachments_count = is_array( $payload['attachment_ids'] ) ? count( $payload['attachment_ids'] ) : 0;
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_ATTACHMENTS_COUNT, $attachments_count );
    update_post_meta( $request_id, KERMANCOPPER_AD_REQUEST_META_SEEN, '0' );
    $admin_email = get_option( 'admin_email' );
    $request_link = admin_url( 'edit.php?post_type=kermancopper_ad&page=kermancopper-ad-requests&request_id=' . $request_id );
    if ( $admin_email ) {
        $ad_title = get_the_title( $ad_id );
        $message_lines = array(
            'درخواست جدید ثبت شد.',
            'آگهی: ' . $ad_title,
            'نام: ' . $payload['name'],
            'موبایل: ' . $payload['mobile'],
            'ایمیل: ' . $payload['email'],
            'لینک جزئیات: ' . $request_link,
        );
        wp_mail( $admin_email, 'درخواست جدید آگهی', implode( "\n", $message_lines ) );
    }
    delete_transient( 'kermancopper_ad_otp_' . $otp_token );
    
    $dashboard_url = add_query_arg(
        array(
            'tab'                => 'requests',
            'registration_notice' => $is_existing ? 'existing' : 'new',
        ),
        kermancopper_ads_get_dashboard_url()
    );
    
    if ( wp_doing_ajax() ) {
        wp_send_json_success( array(
            'message'      => 'درخواست شما با موفقیت ثبت شد.',
            'redirect_url' => $dashboard_url
        ) );
    }
    wp_safe_redirect( $dashboard_url );
    exit;
}
